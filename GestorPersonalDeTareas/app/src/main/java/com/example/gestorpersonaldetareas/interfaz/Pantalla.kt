package com.example.gestorpersonaldetareas.interfaz

// Enumeración que contiene las diferentes pantallas
// por las que podremos navegar dentro de la aplicación.
enum class Pantalla {

    // Pantalla principal: muestra el listado de tareas personales.
    PRINCIPAL,

    // Pantalla del formulario: permite crear o editar tareas.
    FORMULARIO,

    // Pantalla que mostrará las tareas obtenidas mediante la API.
    EJEMPLOS
}